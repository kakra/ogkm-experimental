#!/bin/bash
# Export the series of the current release from driver/ to patches/<release>/.
#
# Usage: tools/export-series.sh [--summary] [<release>]
#
# The patch files, series and README.md in patches/<release>/ are generated
# and replaced on every run. sources.tsv is maintained by hand and maps each
# patch subject to its source; README.md is built from it. Nothing is
# committed.
#
# With --summary, also write a commit message for the export to
# build/export-message.txt (use with git commit -F). It lists the patches
# that were added, removed or changed since the submodule pin of HEAD, from
# git range-diff: changed commit message lines in full, changed code only as
# a line count per file.

source "$(dirname "$0")/lib.sh"

summary=
if [[ ${1-} == --summary ]]; then
	summary=1
	shift
fi
check_release "${1-}"
check_driver

OUT="$TOP/patches/$RELEASE"
SOURCES="$OUT/sources.tsv"
mkdir -p "$OUT"
find "$OUT" -maxdepth 1 -name '*.patch' -delete

# --zero-commit, --no-signature and --no-numbered keep re-exports free of
# noise: a patch file only changes when the patch itself changes, not when
# other patches are added or removed.
git -C "$DRIVER" format-patch -q --zero-commit --no-signature --no-numbered \
	-o "$OUT" "refs/tags/$RELEASE..HEAD"

(cd "$OUT" && ls -1 -- *.patch) >"$OUT/series"

source_of() {
	[[ -f $SOURCES ]] || return 0
	awk -F'\t' -v s="$1" '$1 == s { print $2; exit }' "$SOURCES"
}

missing=0
{
	echo "# Series for driver release $RELEASE"
	echo
	echo "Generated by \`tools/export-series.sh\` from branch \`$BRANCH\`"
	echo "($(git -C "$DRIVER" rev-list --count "refs/tags/$RELEASE..HEAD") patches on top of the upstream tag \`$RELEASE\`)."
	echo "Do not edit; change the fork branch or \`sources.tsv\` and re-export."
	echo
	echo "Apply with \`git am patches/$RELEASE/*.patch\` on the upstream tag \`$RELEASE\`."
	echo
	echo "| # | Patch | Author | Source |"
	echo "|---|---|---|---|"
	n=0
	git -C "$DRIVER" log --reverse --format='%an%x09%s' "refs/tags/$RELEASE..HEAD" |
		while IFS=$'\t' read -r author subject; do
			n=$((n + 1))
			file=$(sed -n "${n}p" "$OUT/series")
			src=$(source_of "$subject")
			if [[ -z $src ]]; then
				echo "warning: no entry in sources.tsv for: $subject" >&2
				src="?"
			fi
			printf '| %d | [%s](%s) | %s | %s |\n' "$n" "${subject//|/\\|}" "$file" "$author" "$src"
		done
} >"$OUT/README.md"

# Report entries in sources.tsv that no longer match a patch.
if [[ -f $SOURCES ]]; then
	git -C "$DRIVER" log --format='%s' "refs/tags/$RELEASE..HEAD" | sort >"$OUT/.subjects"
	cut -f1 "$SOURCES" | grep -v '^#' | sort | comm -23 - "$OUT/.subjects" |
		sed 's/^/warning: stale entry in sources.tsv: /' >&2
	rm -f "$OUT/.subjects"
fi

echo "Exported $(wc -l <"$OUT/series") patches to ${OUT#"$TOP"/}"

[[ -n $summary ]] || exit 0

old=$(git -C "$TOP" rev-parse -q --verify HEAD:driver) || die "no submodule pin in HEAD to compare with"
new=$(git -C "$DRIVER" rev-parse HEAD)
git -C "$DRIVER" cat-file -e "$old^{commit}" 2>/dev/null ||
	die "old pin ${old:0:8} is not available in driver/ (fetch it, or write the message by hand)"
MSG="$TOP/build/export-message.txt"
mkdir -p "$TOP/build"
{
	echo "patches: update the $RELEASE series"
	echo
	echo "Changes to $BRANCH (git range-diff ${old:0:8}...${new:0:8}):"
	echo
	git -C "$DRIVER" range-diff --no-color "refs/tags/$RELEASE..$old" "refs/tags/$RELEASE..$new" |
		awk '
		function flush() {
			for (f in count)
				printf "    %s: %d changed lines\n", f, count[f]
			delete count
		}
		/^ *([0-9]+|-): +([0-9a-f]+|-+) [=!<>] / {
			flush()
			keep = ($3 != "=")
			if (keep)
				print
			section = ""
			next
		}
		!keep { next }
		/^    [ +-]? ## .* ##$/ {
			line = $0
			sub(/^    [ +-]? ## /, "", line)
			sub(/ ##$/, "", line)
			section = (line == "Commit message") ? "msg" : line
			next
		}
		/^    [ +-]?@@ / {
			# Hunk header: "@@ Commit message", "@@ Metadata" or "@@ <file>: ..."
			line = $0
			sub(/^    [ +-]?@@ /, "", line)
			if (line ~ /^(Commit message|Metadata)/)
				section = "msg"
			else if (line != "") {
				sub(/:.*/, "", line)
				section = line
			}
			next
		}
		section == "msg" && /^    [-+]/ { print; next }
		section != "" && section != "msg" && /^    [-+]/ { count[section]++ }
		END { flush() }' |
		# No links to upstream pull requests or issues in commit messages:
		# every push would add an entry to their timeline.
		sed -E -e 's#https://github\.com/([^/ ]+/[^/ ]+)/pull/([0-9]+)#\1 PR \2#g' \
			-e 's#https://github\.com/([^/ ]+/[^/ ]+)/issues/([0-9]+)#\1 issue \2#g' \
			-e 's@([[:alnum:]_.-]+/[[:alnum:]_.-]+)#([0-9]+)@\1 \2@g' \
			-e 's@([^[:alnum:]/])#([0-9]+)@\1\2@g'
} >"$MSG"
echo "Commit message written to ${MSG#"$TOP"/}"
